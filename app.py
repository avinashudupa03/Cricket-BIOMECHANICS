def _list_processed_videos():
    """Return *every* processed video as metadata dicts, newest first.

    Shared by the dashboard (recents) and the full analysis history page.
    """
    items = []
    if not OUTPUT_DATA.exists():
        return items

    features_file = OUTPUT_DATA / "cricket_biomechanics_dataset_engineered.csv"
    name_map = {}
    if features_file.exists():
        try:
            df = pd.read_csv(features_file)
            if "video_name" in df.columns and "shot_type" in df.columns:
                name_map = dict(
                    zip(df["video_name"].astype(str), df["shot_type"])
                )
        except Exception:
            name_map = {}

    for folder in OUTPUT_DATA.iterdir():
        if not folder.is_dir():
            continue
        feat = folder / "biomechanics_features.csv"
        if not feat.exists():
            continue
        name = folder.name
        shot = name_map.get(name, "")
        rating = None
        rating_file = folder / "shot_rating.csv"
        if rating_file.exists():
            try:
                rdf = pd.read_csv(rating_file)
                if not rdf.empty and "rating" in rdf.columns:
                    rating = float(rdf["rating"].iloc[0])
            except Exception:
                rating = None

        frames = None
        landmarks_file = folder / "batting_landmarks.csv"
        if landmarks_file.exists():
            try:
                frames = len(pd.read_csv(landmarks_file, usecols=["frame"]))
            except Exception:
                frames = None

        items.append((folder.name, shot, folder.stat().st_mtime,
                      rating, frames))

    items.sort(key=lambda t: t[2], reverse=True)
    out = []
    for name, shot, mtime, rating, frames in items:
        analysis = OUTPUT_VIDEOS / f"{name}_analysis.mp4"
        out.append({
            "name": name,
            "shot_type": shot,
            "rating": rating,
            "frames": frames,
            "processed_at": time.strftime(
                "%Y-%m-%d %H:%M", time.localtime(mtime)),
            "analysis_exists": analysis.exists(),
            "results_url": url_for("results", video_name=name,
                                   shot_type=shot) if shot else
                            url_for("results", video_name=name),
        })
    return out


def load_injury_data(video_name):
    """Read the injury risk / batsman safety outputs for a processed video.

    Returns a dict with the summary row and the list of detected flags, or an
    empty structure when the analysis has not been produced yet. Never raises -
    a missing/incomplete file degrades to "no data" instead of a 500.
    """
    video_name = Path(video_name).name
    folder = OUTPUT_DATA / video_name
    data = {
        "summary": None,
        "flags": [],
        "available": False,
    }
    summary_file = folder / "injury_risk_summary.csv"
    if summary_file.exists():
        try:
            row = pd.read_csv(summary_file).iloc[0]
            data["summary"] = {
                "safety_score": float(row.get("safety_score", 0.0)),
                "risk_level": str(row.get("risk_level", "")),
                "coverage": float(row.get("coverage", 0.0)),
                "n_flags": int(row.get("n_flags", 0)),
                "top_concern": str(row.get("top_concern", "")),
                "summary": str(row.get("summary", "")),
            }
            data["available"] = True
        except Exception as exc:
            print(f"[load_injury_data] summary failed for {video_name}: {exc}")

    flags_file = folder / "injury_risk.csv"
    if flags_file.exists():
        try:
            df = pd.read_csv(flags_file)
            for _, r in df.iterrows():
                data["flags"].append({
                    "metric": str(r.get("metric", "")),
                    "label": str(r.get("metric_label", "")),
                    "side": str(r.get("side", "")),
                    "severity": str(r.get("severity", "mild")),
                    "frames": int(r.get("frames", 0) or 0),
                    "pct": float(r.get("pct_total", 0.0) or 0.0),
                    "peak": float(r.get("peak_value", 0.0) or 0.0),
                    "units": str(r.get("value_units", "")),
                    "worst_phase": str(r.get("worst_phase", "")),
                    "description": str(r.get("description", "")),
                    "cue": str(r.get("cue", "")),
                })
        except Exception as exc:
            print(f"[load_injury_data] flags failed for {video_name}: {exc}")

    return data


