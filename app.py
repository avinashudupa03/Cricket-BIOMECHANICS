PIPELINE_STEP_LABELS = {
    "main.py": "Detecting player pose & landmarks",
    "angle_calculator.py": "Calculating joint angles",
    "phase_detector.py": "Detecting batting phases",
    "biomechanics_analyzer.py": "Extracting biomechanics features",
    "shot_rater.py": "Rating the shot (0-10)",
    "injury_risk.py": "Screening injury & batsman safety",
    "output_video.py": "Rendering annotated analysis video",
}
PIPELINE_JOBS = {}
PIPELINE_JOBS_LOCK = threading.Lock()

# Batch processing state (keyed by batch_id)
BATCH_JOBS = {}
BATCH_JOBS_LOCK = threading.Lock()
MAX_JOBS = 400


def _prune_old_jobs():
    """Drop finished jobs older than a day so the registry cannot grow forever."""
    cutoff = time.time() - 86400
    with PIPELINE_JOBS_LOCK:
        for jid in [j for j, job in PIPELINE_JOBS.items()
                    if job.get("done") and (job.get("finished_at") or 0) < cutoff]:
            PIPELINE_JOBS.pop(jid, None)


def _pipeline_worker(job_id):
    job = PIPELINE_JOBS[job_id]
    job["current"] = "Starting analysis…"
    job["started_at"] = time.time()
    video_path = Path(job["video_path"])
    command = [
        sys.executable,
        str(BASE_DIR / "process_video.py"),
        str(video_path),
    ]
    try:
        env = dict(os.environ)
        env["PYTHONUNBUFFERED"] = "1"
        proc = subprocess.Popen(
            command,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            encoding="utf-8",
            errors="replace",
            cwd=str(BASE_DIR),
            env=env,
            creationflags=config.NO_CONSOLE_FLAGS,
        )
        for line in proc.stdout:
            line = line.strip()
            if line.startswith("RUNNING:"):
                matched = False
                for token, label in PIPELINE_STEP_LABELS.items():
                    if token in line:
                        if label not in job["steps"]:
                            job["steps"].append(label)
                        job["current"] = label
                        matched = True
                        break
                if not matched:
                    job["current"] = line[len("RUNNING:"):].strip()
            elif "COMPLETE" in line:
                job["current"] = "Finalising results…"
        proc.wait()
        job["ok"] = proc.returncode == 0
        if not job["ok"]:
            job["error"] = "Processing failed on the server — see the console log."
    except Exception as exc:
        print(f"[pipeline] job {job_id} crashed: {exc}")
        job["ok"] = False
        job["error"] = f"Processing crashed: {exc}"

    if job["ok"]:
        job["video_name"] = video_path.stem
    job["current"] = "Done" if job["ok"] else "Failed"
    with PIPELINE_JOBS_LOCK:
        job["done"] = True
        job["finished_at"] = time.time()
    _release_inflight(job)


def _release_inflight(job):
    """Release the upload-dedup lock once a queued clip finishes processing."""
    digest = job.get("digest")
    if digest:
        with UPLOAD_LOCK:
            INFLIGHT_UPLOADS.discard(digest)


def load_video_results(video_name):
    """Read biomechanics results for a processed video from its CSV files."""
    video_name = Path(video_name).name
    folder = OUTPUT_DATA / video_name
    features_file = folder / "biomechanics_features.csv"
    landmarks_file = folder / "batting_landmarks.csv"

    data = {
        "video_name": video_name,
        "frames": None,
        "found": features_file.exists(),
        "impact_angles": {},
        "metrics": {},
        "features": {},
        "rating": None,
    }

    if landmarks_file.exists():
        try:
            data["frames"] = len(
                pd.read_csv(landmarks_file, usecols=["frame"])
            )
        except Exception:
            data["frames"] = None

    if not features_file.exists():
        return data

    try:
        row = pd.read_csv(features_file).iloc[0].to_dict()
    except Exception:
        return data

    data["features"] = row

    metric_keys = [
        "impact_frame",
        "impact_time_ms",
        "downswing_duration_ms",
        "followthrough_duration_ms",
        "maximum_movement_score",
        "average_movement_score",
    ]
    for key in metric_keys:
        if key in row:
            data["metrics"][key] = row[key]

    for col in IMPACT_ANGLE_COLUMNS:
        if col in row:
            data["impact_angles"][col] = row[col]

    # Shot rating - computed deterministically by the reusable module. The
    # per-frame extra data activates balance/backlift/stride factors. Any
    # per-video data glitch must never 500 the whole results page, so a
    # failure here degrades to a missing rating instead.
    data["rating"] = None
    try:
        data["rating"] = shot_rating.rating_to_dict(
            shot_rating.rate_shot(
                row, extra=shot_rating.build_extra(video_name)
            )
        )
    except Exception as exc:
        print(f"[load_video_results] rating failed for {video_name}: {exc}")

    return data


def make_angle_plot(video_name):
    """Generate a multi-panel angle time-series plot from batting_angles.csv.

    Returns the filename of the saved plot, or None on failure. The plot is
    only regenerated when missing - results pages stay fast on repeat loads.
    """
    plot_name = "angle_plot.png"
    out = OUTPUT_DATA / video_name / plot_name
    if out.exists():
        return plot_name
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt

        angles_file = OUTPUT_DATA / video_name / "batting_angles.csv"
        if not angles_file.exists():
            return None

        df = pd.read_csv(angles_file)
        angle_cols = [
            c for c in df.columns
            if c not in {"frame", "timestamp_ms"}
        ]
        if not angle_cols:
            return None

        t_ms = df["timestamp_ms"].to_numpy()

        n = len(angle_cols)
        cols = 2
        rows = int((n + 1) / 2)
        fig, axes = plt.subplots(rows, cols, figsize=(12, 3.2 * rows))
        axes = axes.flatten()

        for idx, col in enumerate(angle_cols):
            ax = axes[idx]
            ax.plot(t_ms, df[col], lw=1.5)
            ax.set_title(col, fontsize=9)
            ax.set_xlabel("time (ms)")
            ax.set_ylabel("angle (deg)")
            ax.grid(True, alpha=0.3)

        for idx in range(n, len(axes)):
            axes[idx].axis("off")

        fig.suptitle(f"Joint Angles - {video_name}", fontsize=13)
        fig.tight_layout(rect=[0, 0, 1, 0.97])

        plot_name = "angle_plot.png"
        out = OUTPUT_DATA / video_name / plot_name
        fig.savefig(out, dpi=130)
        plt.close(fig)
        return plot_name
    except Exception as exc:
        print(f"[make_angle_plot] {exc}")
        return None


def load_dataset_stats():
    """Return dataset stats read dynamically from the dataset CSV.

    Falls back gracefully when the dataset has not been built yet.
    """
    stats = {
        "total_videos": 0,
        "n_classes": 0,
        "class_names": [],
        "distribution": {},
        "n_features": 0,
        "dataset_exists": False,
        "has_ml_reports": {
            "comparison": (REPORTS_DIR / "model_comparison.csv").exists(),
            "confusion": (REPORTS_DIR / "confusion_matrix.png").exists(),
            "importance": (REPORTS_DIR / "feature_importance.png").exists(),
            "summary": (REPORTS_DIR / "model_results_summary.txt").exists(),
        },
    }

    dataset_files = [
        OUTPUT_DATA / "cricket_biomechanics_dataset_engineered.csv",
        OUTPUT_DATA / "cricket_biomechanics_dataset_cleaned.csv",
        OUTPUT_DATA / "cricket_biomechanics_dataset.csv",
    ]
    chosen = None
    for path in dataset_files:
        if path.exists():
            chosen = path
            break

    if chosen is None:
        return stats

    try:
        df = pd.read_csv(chosen)
        stats["dataset_exists"] = True
        stats["total_videos"] = len(df)
        stats["distribution"] = (
            df["shot_type"].value_counts().to_dict()
            if "shot_type" in df.columns else {}
        )
        stats["class_names"] = list(stats["distribution"].keys())
        stats["n_classes"] = len(stats["class_names"])
        stats["n_features"] = len(
            [c for c in df.columns if c not in
             {"video_name", "shot_type"}]
        )
    except Exception as exc:
        print(f"[load_dataset_stats] {exc}")

    return stats


