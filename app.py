def ensure_analysis_video(video_name):
    """Ensure the annotated analysis video exists for a clip.

    If it is missing, it is rebuilt from the existing per-video CSVs
    (no MediaPipe re-run) via ``output_video.py`` (H.264, browser-playable).
    Runs headless: no OpenCV window, no child console. Returns True on success.
    """
    video_name = Path(video_name).stem
    out = OUTPUT_VIDEOS / f"{video_name}_analysis.mp4"
    if out.exists() and analysis_video_is_ready(out):
        return True

    source = None
    for folder in INPUT_VIDEOS.rglob("*"):
        if folder.is_file() and folder.stem == video_name \
                and not is_generated_video(folder.name):
            source = folder
            break
    if source is None:
        return False

    shot_type = source.parent.name
    temp_out = out.with_name(f"{out.stem}.regenerating.mp4")
    try:
        temp_out.unlink(missing_ok=True)
    except OSError as exc:
        print(f"[ensure_analysis_video] could not clear temporary output: {exc}")
        return False
    command = [
        sys.executable,
        str(BASE_DIR / "output_video.py"),
        str(source),
        shot_type,
        str(temp_out),
    ]
    try:
        result = subprocess.run(
            command,
            capture_output=True,
            text=True,
            cwd=str(BASE_DIR),
            timeout=900,
            creationflags=config.NO_CONSOLE_FLAGS,
        )
        if result.returncode != 0 or not temp_out.exists():
            return False
        try:
            os.replace(temp_out, out)
        except OSError as exc:
            print(f"[ensure_analysis_video] could not replace output: {exc}")
            return False
        return True
    except Exception as exc:
        print(f"[ensure_analysis_video] {exc}")
        return False


def analysis_video_is_ready(path):
    """Return whether an analysis video is readable and non-empty.

    Reliability only - the duration/frame-fidelity of the output is guaranteed
    by output_video.py's VIDEO VALIDATION block, not by a minimum-seconds
    gate here. Short clips are valid and must not be hidden or padded.
    """
    capture = cv2.VideoCapture(str(path))
    try:
        fps = capture.get(cv2.CAP_PROP_FPS)
        frames = capture.get(cv2.CAP_PROP_FRAME_COUNT)
        return fps > 0 and frames > 0
    finally:
        capture.release()


