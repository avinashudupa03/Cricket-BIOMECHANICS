def load_phase_timeline(video_name):
    """Return phase segments + key frames from batting_phases.csv."""
    phases_file = OUTPUT_DATA / video_name / "batting_phases.csv"
    if not phases_file.exists():
        return None
    try:
        df = pd.read_csv(phases_file)
    except Exception:
        return None

    segs = []
    current = None
    for _, row in df.iterrows():
        ph = str(row["phase"])
        fr = int(row["frame"])
        if current is None or current["phase"] != ph:
            if current is not None:
                current["end"] = fr
            current = {"phase": ph, "start": fr, "end": None}
            segs.append(current)
        else:
            current["end"] = fr
    if current is not None and current["end"] is None:
        current["end"] = int(df["frame"].iloc[-1])

    total = int(df["frame"].iloc[-1]) if len(df) else 0
    impact = df[df["phase"] == "Impact"]["frame"]
    impact_frame = int(impact.iloc[len(impact) // 2]) if len(impact) else None

