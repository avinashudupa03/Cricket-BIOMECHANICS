def normalise_shot_type(value):
    """Return the canonical slug for a shot-type label, or None if unknown.

    "Pull Shot" is a multi-word class, so callers may spell it with a space
    ("pull shot"), with an underscore ("pull_shot") or in mixed case. All three
    collapse to the single slug that matches the input_videos/ folder name, so
    uploads can never land in a second, parallel pull-shot folder.
    """
    if value is None:
        return None
    slug = " ".join(str(value).strip().lower().replace("_", " ").split())
    return slug if slug in SHOT_TYPES else None

