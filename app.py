def safe_filename(name):
    keep = "".join(c for c in name if c.isalnum() or c in "-_")
    return keep or "video"


def video_content_hash(path, chunk_size=1024 * 1024):
    """Return a stable digest used to prevent identical uploads."""
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(chunk_size), b""):
            digest.update(chunk)
    return digest.hexdigest()


# Serialises the dedup-then-move upload step so two simultaneous identical
# submissions can never create two input files.
UPLOAD_LOCK = threading.Lock()
# SHA-256 digests of uploads currently being scheduled into the pipeline.
# A repeat submit for the same clip while one is already in flight is
# short-circuited instead of written a second time.
INFLIGHT_UPLOADS = set()


def find_existing_video(path, digest=None):
    """Find an existing uploaded source with identical contents.

    Only files with the same byte size as the upload are hashed (fast
    pre-filter), and generated pipeline outputs are never treated as inputs.
    """
    if digest is None:
        digest = video_content_hash(path)
    try:
        size = path.stat().st_size
    except OSError:
        return None
    for candidate in INPUT_VIDEOS.rglob("*"):
        if candidate == path or not candidate.is_file():
            continue
        if candidate.suffix.lower() not in ALLOWED_EXTENSIONS:
            continue
        if is_generated_video(candidate.name):
            continue
        try:
            if candidate.stat().st_size != size:
                continue
        except OSError:
            continue
        if video_content_hash(candidate) == digest:
            return candidate
    return None


def make_unique_path(folder, stem, ext):
    """Return a Path inside `folder` that does not already exist.

    Appends -1, -2, ... to the stem when a name collision exists so an
    uploaded file never silently overwrites an existing one. The name is also
    checked against the processed-output folders so two uploaded clips sharing
    a stem will never write into the same output_data / analysis folder.
    """
    folder.mkdir(parents=True, exist_ok=True)

    def _taken(candidate_stem):
        candidate = folder / f"{candidate_stem}{ext}"
        if candidate.exists():
            return True
        # Same stem must not collide with an existing processed video.
        if (OUTPUT_DATA / candidate_stem).exists():
            return True
        if (ANALYSIS_VIDEOS / f"{candidate_stem}_analysis.mp4").exists():
            return True
        return False

    stem0 = stem
    counter = 1
    while _taken(stem):
        stem = f"{stem0}-{counter}"
        counter += 1
    return folder / f"{stem}{ext}"


def run_pipeline(video_path):
    """Run the existing per-video pipeline via process_video.py.

    Returns the process stdout/stderr so errors can be surfaced cleanly,
    without leaking raw tracebacks to the user.
    """
    command = [
        sys.executable,
        str(BASE_DIR / "process_video.py"),
        str(video_path),
    ]
    try:
        result = subprocess.run(
            command,
            capture_output=True,
            text=True,
            cwd=str(BASE_DIR),
            timeout=3600,
            creationflags=config.NO_CONSOLE_FLAGS,
        )
    except (subprocess.TimeoutExpired,
            subprocess.SubprocessError, OSError) as exc:
        print(f"[run_pipeline] {exc}")
        return type("Result", (), {
            "returncode": 1, "stdout": "", "stderr": str(exc)
        })()
    return result


