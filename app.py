def load_ml_insights():
    """Read ML eval info (best model, accuracy, method) from report files."""
    insights = {
        "available": False,
        "dataset_size": None,
        "n_classes": None,
        "best_model": None,
        "evaluation": "Leave-One-Out CV (LOOCV)",
        "accuracy": None,
        "accuracy_raw": None,
        "comparison_table": None,  # list of dict rows
    }

    summary = REPORTS_DIR / "model_results_summary.txt"
    if summary.exists():
        try:
            text = summary.read_text(encoding="utf-8")
            m = re.search(r"Dataset size\s*:?\s*(\d+)", text, re.I)
            if m:
                insights["dataset_size"] = int(m.group(1))
            m = re.search(r"Best model\s*:?\s*([A-Za-z]+)", text)
            if m:
                insights["best_model"] = m.group(1)
            m = re.search(
                r"LOOCV accuracy\s*:?\s*([0-9.]+)",
                text, re.I
            )
            if m:
                insights["accuracy_raw"] = float(m.group(1))
                insights["accuracy"] = f"{float(m.group(1)) * 100:.1f}%"
            m = re.search(r"Shot classes\s*:?\s*(\d+)", text, re.I)
            if m:
                insights["n_classes"] = int(m.group(1))
        except Exception as exc:
            print(f"[load_ml_insights] summary: {exc}")

    comp = REPORTS_DIR / "model_comparison.csv"
    rows = []
    if comp.exists():
        try:
            df = pd.read_csv(comp)
            for _, r in df.iterrows():
                rows.append({
                    "model": r.get("model", ""),
                    "accuracy": r.get("accuracy"),
                    "f1_macro": r.get("f1_macro"),
                    "precision_macro": r.get("precision_macro"),
                    "recall_macro": r.get("recall_macro"),
                })
        except Exception as exc:
            print(f"[load_ml_insights] comparison: {exc}")

    if insights["best_model"] or insights["accuracy_raw"] is not None:
        insights["available"] = True
    insights["comparison_table"] = rows
    return insights


